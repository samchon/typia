import {
  OpenApi,
  OpenApiV3,
  OpenApiV3_1,
  OpenApiV3_2,
  SwaggerV2,
} from "@typia/interface";
import { OpenApiConverter } from "@typia/utils";
import fs from "fs";
import typia from "typia";

import { TestGlobal } from "../../TestGlobal";

/**
 * Verifies every example document downgrades to a valid OpenAPI 3.1 document.
 *
 * Downgrading real documents exercises every conversion branch; the result must
 * satisfy the OpenApiV3_1 declaration.
 *
 * 1. Read each example and validate it natively.
 * 2. Upgrade it and downgrade it to 3.1.
 * 3. Assert the result with the native validator.
 *
 * @evidence contracts/testing.md#behavioral-verification Each example is upgraded, downgraded and checked by a natively generated validator.
 * @evidence contracts/testing.md#independent-expectations The OpenApiV3_1 declaration is the specification and the validator is generated independently of the converter.
 * @evidence contracts/testing.md#distinguishing-cases Every example is a case with structural validity only.
 * @evidence contracts/testing.md#execution-ownership The test-utils test:integration command (DynamicExecutor over src/features under ttsx with the native typia plugin) discovers this exported case. typia.assert validators are generated by the native transform and the examples are read from disk.
 */
export const test_document_downgrade_v31 = async (): Promise<void> => {
  const path: string = `${TestGlobal.ROOT}/examples/v3.1`;
  for (const directory of await fs.promises.readdir(path)) {
    const stats: fs.Stats = await fs.promises.lstat(`${path}/${directory}`);
    if (stats.isDirectory() === false) continue;
    for (const file of await fs.promises.readdir(`${path}/${directory}`)) {
      if (file.endsWith(".json") === false) continue;
      const swagger:
        | SwaggerV2.IDocument
        | OpenApiV3.IDocument
        | OpenApiV3_1.IDocument
        | OpenApiV3_2.IDocument = typia.assert<
        | SwaggerV2.IDocument
        | OpenApiV3.IDocument
        | OpenApiV3_1.IDocument
        | OpenApiV3_2.IDocument
      >(
        JSON.parse(
          await fs.promises.readFile(`${path}/${directory}/${file}`, "utf8"),
        ),
      );
      const openapi: OpenApi.IDocument =
        OpenApiConverter.upgradeDocument(swagger);
      const downgraded: OpenApiV3_1.IDocument =
        OpenApiConverter.downgradeDocument(openapi, "3.1");
      typia.assert(downgraded);
    }
  }
};
