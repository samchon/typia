import { OpenApiV3_1 } from "@typia/interface";

/**
 * Minimal OpenAPI v3.1 document serving one calculator operation.
 *
 * Fixture for the HTTP-controller tests: `POST /calculator/add` takes a `{ x, y
 * }` body and answers `{ value }`, so both the reflected input schema and the
 * structured output path can be asserted without a network.
 *
 * @evidence contracts/testing.md#behavioral-verification This fixture supplies the document consumed by test_langchain_http_controller_standalone; that case checks tool population and description propagation, not network execution.
 * @evidence contracts/testing.md#independent-expectations The authored POST operation, required numeric operands and numeric result are input contracts rather than values generated by the converter under test.
 * @evidence contracts/testing.md#distinguishing-cases The single-operation fixture owns the successful population scenario; coercion and invalid arguments use their sibling cases' separately authored documents.
 * @evidence contracts/testing.md#execution-ownership This exported fixture namespace is not a test entry; node:test registers the standalone consumer in src/unit/index.ts without the native plugin.
 */
export namespace CalculatorApi {
  /** API version declared in the document's `info`. */
  export const VERSION = "3.2.1";

  /**
   * Compose a fresh calculator document for the portable HTTP-tool case.
   *
   * @evidence contracts/testing.md#behavioral-verification The standalone consumer passes this document through HttpLlm.controller and toLangChainTools and asserts operation-name/count propagation and a description.
   * @evidence contracts/testing.md#independent-expectations Its numeric operand/result schemas and Add two numbers description are authored independently of both converters.
   * @evidence contracts/testing.md#distinguishing-cases Each call supplies one POST operation with required x/y; separate HTTP coercion and validation cases own argument verdicts.
   * @evidence contracts/testing.md#execution-ownership This function is fixture preparation called by test_langchain_http_controller_standalone in the plugin-free node:test population; it performs no HTTP request.
   */
  export const document = (): OpenApiV3_1.IDocument => ({
    openapi: "3.1.0",
    info: { title: "Calculator API", version: VERSION },
    paths: {
      "/calculator/add": {
        post: {
          description: "Add two numbers.",
          requestBody: {
            required: true,
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    x: { type: "number" },
                    y: { type: "number" },
                  },
                  required: ["x", "y"],
                },
              },
            },
          },
          responses: {
            "200": {
              description: "Sum of the two numbers.",
              content: {
                "application/json": {
                  schema: {
                    type: "object",
                    properties: {
                      value: { type: "number" },
                    },
                    required: ["value"],
                  },
                },
              },
            },
          },
        },
      },
    },
    components: {},
  });
}
