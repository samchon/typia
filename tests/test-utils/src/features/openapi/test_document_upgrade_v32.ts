import { OpenApi, OpenApiV3_2 } from "@typia/interface";
import { OpenApiConverter } from "@typia/utils";
import fs from "fs";
import typia from "typia";

import { TestGlobal } from "../../TestGlobal";

/**
 * Verifies every OpenAPI 3.2 example upgrades with its query methods kept.
 *
 * 3.2 adds the query method; the upgraded document must keep each query
 * operation.
 *
 * 1. Read each v3.2 example and validate it natively.
 * 2. Upgrade it and validate the result.
 * 3. Assert every source query path still has a query operation.
 *
 * @evidence contracts/testing.md#behavioral-verification Each example is upgraded, validated natively and every query operation of the source must exist in the result.
 * @evidence contracts/testing.md#independent-expectations The expectation is read from the source document's own paths, not from the converter.
 * @evidence contracts/testing.md#distinguishing-cases Only documents containing query operations exercise the preservation check.
 * @evidence contracts/testing.md#execution-ownership The test-utils test:integration command (DynamicExecutor over src/features under ttsx with the native typia plugin) discovers this exported case. typia.assert validators are generated by the native transform and the examples are read from disk.
 */
export const test_document_upgrade_v32 = async (): Promise<void> => {
  const path: string = `${TestGlobal.ROOT}/examples/v3.2`;
  for (const file of await fs.promises.readdir(path)) {
    if (file.endsWith(".json") === false) continue;
    const swagger: OpenApiV3_2.IDocument = typia.assert<OpenApiV3_2.IDocument>(
      JSON.parse(await fs.promises.readFile(`${path}/${file}`, "utf8")),
    );
    const openapi: OpenApi.IDocument =
      OpenApiConverter.upgradeDocument(swagger);
    typia.assert(openapi);

    // Verify query method is preserved
    if (swagger.paths) {
      for (const [pathKey, pathItem] of Object.entries(swagger.paths)) {
        if (pathItem?.query !== undefined) {
          const upgradedPath = openapi.paths?.[pathKey];
          if (upgradedPath?.query === undefined) {
            throw new Error(
              `Query method was not preserved for path ${pathKey}`,
            );
          }
        }
      }
    }
  }
};
