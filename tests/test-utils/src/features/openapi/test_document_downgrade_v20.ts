import {
  OpenApi,
  OpenApiV3,
  OpenApiV3_1,
  OpenApiV3_2,
  SwaggerV2,
} from "@typia/interface";
import { TestEquality } from "@typia/template/equality";
import { OpenApiConverter } from "@typia/utils";
import fs from "fs";
import path from "path";
import typia from "typia";

import { TestGlobal } from "../../TestGlobal";
import { _readJsonFixturePaths } from "../../internal/_readJsonFixturePaths";

/**
 * Verifies example documents downgrade to Swagger 2.0 or fail with the exact
 * unrepresentable reason.
 *
 * Swagger 2.0 has no server description field and no named response examples,
 * so the lossless downgrader must reject a document using either instead of
 * dropping it. The checked-in 3.1 examples all use one of them, while the 2.0
 * examples are representable; each side pins its own branch of the converter.
 *
 * 1. Read each 3.1 and 2.0 example and validate it natively.
 * 2. Derive the expected rejection from the raw document and the Swagger 2.0
 *    contract, then upgrade and downgrade it to 2.0.
 * 3. Assert the exact rejection message, or for a representable document its
 *    version, info, paths and operations and the native SwaggerV2 guard.
 *
 * @evidence contracts/testing.md#behavioral-verification Each example is upgraded and downgraded through the public converter. A rejected document must throw the exact message; a representable one must keep its version, info, paths and operations and satisfy the native guard, so a converter that drops a server description or example, or rejects a representable document, fails.
 * @evidence contracts/testing.md#independent-expectations The expected rejection comes from the Swagger 2.0 contract, which has no server description and no per-name response examples, evaluated on the raw JSON rather than on the converter's upgraded output. The output shape is the SwaggerV2 declaration through a validator generated independently of the converter.
 * @evidence contracts/testing.md#distinguishing-cases Positive and negative twins come from different examples: the 3.1 bbs and shopping examples carry a server description and wanted carries response named examples, while the 2.0 examples have neither and must downgrade. The case fails when either side is empty, so a population that never reaches one branch cannot pass.
 * @evidence contracts/testing.md#execution-ownership The test-utils test:integration command (DynamicExecutor over src/features under ttsx with the native typia plugin) discovers this exported case. typia.assert validators are generated by the native transform and the examples are read from disk.
 * @evidence contracts/e2e.md#necessary-boundary Checked-in documents pass through native input guards, upgrade and downgrade conversion and the native output guard for the 2.0 contract. The shared reader selects flat and nested JSON and rejects empty populations, so success must exercise a document. Structural guards do not establish complete semantic equivalence.
 * @evidence contracts/e2e.md#shared-execution This case shares the test-utils integration project and native-plugin artifact lifecycle with the other src/features exports. Its runtime rows reuse emitted schemas/callbacks in this invocation instead of starting a compiler host per input; it performs no independent installation or host launch.
 * @evidence contracts/e2e.md#state-isolation-and-reuse-validity Each invocation owns its schema/definition objects and payloads; document callers parse fresh text before conversion. Compiler-artifact reuse cannot supply a prior runtime verdict. This case opens no persistent service/process handle; fixture-reader unit temporary files are owned and released by that separate unit.
 * @evidence contracts/e2e.md#preserved-coverage The earlier loop only visited sub-directories, so the flat 3.1 examples were never downgraded and the case passed without exercising a document. It now reads flat and nested files, rejects an empty population and asserts both the rejected and the downgraded branch. Producer parity and structural acceptance retain their stated oracle limits rather than certifying semantic correctness.
 */
export const test_document_downgrade_v20 = async (): Promise<void> => {
  let rejected: number = 0;
  let downgraded: number = 0;
  for (const file of [
    ...(await _readJsonFixturePaths(`${TestGlobal.ROOT}/examples/v3.1`)),
    ...(await _readJsonFixturePaths(`${TestGlobal.ROOT}/examples/v2.0`)),
  ]) {
    const raw: Record<string, any> = JSON.parse(
      await fs.promises.readFile(file, "utf8"),
    );
    const swagger:
      | SwaggerV2.IDocument
      | OpenApiV3.IDocument
      | OpenApiV3_1.IDocument
      | OpenApiV3_2.IDocument = typia.assert<
      | SwaggerV2.IDocument
      | OpenApiV3.IDocument
      | OpenApiV3_1.IDocument
      | OpenApiV3_2.IDocument
    >(raw);
    const openapi: OpenApi.IDocument =
      OpenApiConverter.upgradeDocument(swagger);

    const title: string = path.basename(file);
    const result: { document?: SwaggerV2.IDocument } = {};
    TestEquality.equals(
      `${title} rejection`,
      TestEquality.thrown(() => {
        result.document = OpenApiConverter.downgradeDocument(openapi, "2.0");
      }),
      expectRejection(raw),
    );
    if (result.document === undefined) {
      ++rejected;
      continue;
    }
    ++downgraded;
    typia.assert(result.document);
    TestEquality.equals(`${title} version`, result.document.swagger, "2.0");
    TestEquality.equals(`${title} info`, result.document.info, raw.info);
    TestEquality.equals(
      `${title} paths`,
      Object.keys(result.document.paths ?? {}).sort(),
      Object.keys(raw.paths ?? {}).sort(),
    );
    TestEquality.equals(
      `${title} operations`,
      countOperations(result.document.paths),
      countOperations(raw.paths),
    );
  }
  if (rejected === 0 || downgraded === 0)
    throw new Error(
      `Downgrade population missed a branch: ${rejected} rejected, ${downgraded} downgraded.`,
    );
};

const METHODS: string[] = [
  "get",
  "put",
  "post",
  "delete",
  "options",
  "head",
  "patch",
  "trace",
];

/**
 * Message the downgrader must throw for a document Swagger 2.0 cannot express,
 * or `null` when the document is representable. Server descriptions are checked
 * before responses, matching the order the document is converted in.
 */
const expectRejection = (raw: Record<string, any>): string | null => {
  if (
    Array.isArray(raw.servers) &&
    raw.servers.some((server) => server?.description !== undefined)
  )
    return "SwaggerV2Downgrader: document servers descriptions are not representable.";
  const named: boolean = Object.values<any>(raw.paths ?? {}).some((item) =>
    METHODS.some((method) =>
      Object.values<any>(item?.[method]?.responses ?? {}).some((response) =>
        Object.values<any>(response?.content ?? {}).some(
          (media) => Object.keys(media?.examples ?? {}).length > 0,
        ),
      ),
    ),
  );
  return named
    ? "SwaggerV2Downgrader: response named examples are not representable."
    : null;
};

const countOperations = (paths: Record<string, any> | undefined): number =>
  Object.values<any>(paths ?? {}).reduce(
    (sum: number, item) =>
      sum + METHODS.filter((method) => item?.[method] !== undefined).length,
    0,
  );
